# ---------------------------------------------------------------------------
# Analysis geometry
# ---------------------------------------------------------------------------
FS = 48000.0
M = 1 << 14          # 16384 analysis samples -- the same length the old metric uses
K_BIN = 853          # f0 = K_BIN * FS / M = 2499.0234375 Hz, one bin off the old 2500
F0 = K_BIN * FS / M
LF_HZ = 200.0        # below this, energy is reported as the LF/settling bucket, not as alias

SETTLE_S_OLD = 0.3   # what OSValidationTest discards
SETTLE_S_NEW = 4.0   # 18 tau of the 0.72 Hz output high-passes

SHIPPED_SATNEG = 1.9
PRIOR_SATNEG = 0.76054


def _db(num, den):
    return 10.0 * np.log10((num + 1e-300) / (den + 1e-300))


# ---------------------------------------------------------------------------
# The two metrics
# ---------------------------------------------------------------------------
def metric_old(y, f0=2500.0, fs=FS, n=M):
    """Verbatim reimplementation of OSValidationTest's `aliasFloorDb`.

    Kept exact (Hann, +-3 bin mask, `round(f/f0) >= 1`) so that any difference between the two
    columns of the measurement table is the ANALYSIS and cannot be the render.
    """
    y = np.asarray(y[:n], dtype=float)
    i = np.arange(n)
    win = 0.5 - 0.5 * np.cos(2.0 * np.pi * i / (n - 1))
    mag = np.abs(np.fft.rfft(y * win))
    b = np.arange(len(mag))
    f = b * fs / n
    binhz = fs / n
    nearest = np.round(f / f0)
    is_h = (nearest >= 1.0) & (np.abs(f - nearest * f0) < 3.0 * binhz)
    e = mag ** 2
    e[0] = 0.0                      # the old loop starts at b = 1
    e[len(mag) - 1] = 0.0           # ... and stops before N/2
    return _db(e[~is_h].sum(), e[is_h].sum())


def metric_new(y, k=K_BIN, fs=FS, n=M, lf_hz=LF_HZ):
    """Bin-exact, rectangular-window, LF-separated alias measurement.

    Returns a dict rather than a scalar: the point of the instrument is that the buckets the old
    metric merged stay apart, so a residual can be attributed instead of argued about.
    """
    y = np.asarray(y[:n], dtype=float)
    if len(y) != n:
        raise ValueError(f"metric_new needs exactly {n} samples, got {len(y)}")
    mag = np.abs(np.fft.rfft(y))          # rectangular window: exact for period-n content
    e = mag ** 2
    nbin = len(mag)
    b = np.arange(nbin)

    harm = np.zeros(nbin, dtype=bool)
    order = 1
    while order * k < nbin:
        harm[order * k] = True
        order += 1

    dc = np.zeros(nbin, dtype=bool)
    dc[0] = True
    lf = (b * fs / n < lf_hz) & ~harm & ~dc

    other = ~(harm | dc | lf)
    hp = e[harm].sum()
    return {
        "alias_db": _db(e[other].sum(), hp),          # the headline: inharmonic, LF excluded
        "alias_incl_lf_db": _db(e[other].sum() + e[lf].sum(), hp),
        "lf_db": _db(e[lf].sum(), hp),                # settling / DC-offset residue
        "dc_db": _db(e[0], hp),
        "h_orders": int(harm.sum()),
        "_e": e, "_harm": harm, "_lf": lf, "_other": other,
    }


def strip(d):
    return {kk: vv for kk, vv in d.items() if not kk.startswith("_")}


# ---------------------------------------------------------------------------
# Rendering through the real chain
# ---------------------------------------------------------------------------
def render_sine(amp, os_factor, satneg, fs=FS, k=K_BIN, n=M,
                settle_s=SETTLE_S_NEW, drive=0.85, tmpdir=None):
    """Render a bin-exact sine through OfflineRender; return the settled n-sample tail.

    `--input-ref 1 --output-makeup 1` makes the CLI's gain staging the identity around PedalDSP,
    so `amp` is the same internal-volts amplitude OSValidationTest feeds, and the knob defaults
    below are PedalChain::Params' own defaults -- i.e. this reproduces the test's operating point
    rather than a plausible-looking neighbour of it.
    """
    period = n / k                       # samples per cycle; n samples == exactly k cycles
    settle = int(np.ceil(settle_s * fs / n)) * n     # whole analysis blocks, keeps phase at 0
    total = settle + n + 4096            # a little tail so nothing is read past the end
    t = np.arange(total)
    x = (amp * np.sin(2.0 * np.pi * t / period)).astype(np.float32)

    own_tmp = tmpdir is None
    tmpdir = tmpdir or tempfile.mkdtemp(prefix="alias_gate_")
    tag = f"a{amp}_os{os_factor}_sn{satneg}_fs{int(fs)}_n{n}"
    inp = os.path.join(tmpdir, f"in_{tag}.wav")
    outp = os.path.join(tmpdir, f"out_{tag}.wav")
    wavfile.write(inp, int(fs), x)

    cmd = [RENDER_BIN, "--in", inp, "--out", outp,
           "--os", str(os_factor), "--input-ref", "1", "--output-makeup", "1",
           "--blend", "1", "--level", "1", "--drive", str(drive), "--master", "1",
           "--fit", f"jfetSatNeg={satneg}"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"OfflineRender failed: {' '.join(cmd)}\n{r.stdout}\n{r.stderr}")
    sr, y = wavfile.read(outp)
    assert sr == int(fs), (sr, fs)
    y = np.asarray(y, dtype=float)
    if y.ndim > 1:
        y = y[:, 0]
    if own_tmp:
        for p in (inp, outp):
            try:
                os.remove(p)
            except OSError:
                pass
    return y[settle:settle + n]


# ---------------------------------------------------------------------------
# GATES
# ---------------------------------------------------------------------------
def _tone(n, k, amp=1.0, phase=0.0, length=None):
    """A tone at bin `k` of an n-point DFT, generated over `length` samples (default n).

    `length` exists so a longer buffer can be sliced at several offsets and every slice is still
    exactly periodic in n -- generating with `np.arange(length)/length` instead would silently
    change the frequency and make an offset-invariance test fail for the wrong reason.
    """
    t = np.arange(length if length is not None else n)
    return amp * np.sin(2.0 * np.pi * k * t / n + phase)


def selftest():
    """Six known-answer gates. Returns (n_fail, lines)."""
    out, fails = [], 0

    def rep(name, ok, detail):
        nonlocal fails
        if not ok:
            fails += 1
        out.append(f"  {'PASS' if ok else 'FAIL'}  {name:<44} {detail}")

    n = M
    # ---- KA-1: a pure bin-exact sine has NO alias content -------------------
    y = _tone(n, K_BIN)
    new = metric_new(y)
    old = metric_old(y, f0=F0)
    rep("KA-1 pure sine, new metric at floor",
        new["alias_db"] < -250.0, f"new = {new['alias_db']:.1f} dB")
    out.append(f"        (old metric on the SAME pure sine: {old:.2f} dB "
               f"-- this is the leakage pedestal, not a chain property)")

    # ---- KA-2: harmonics only. Truth = -inf. THE DISCRIMINATOR FOR (a) ------
    # Two versions of ONE signal: on-grid (bin-exact f0) and off-grid at the shipped 2500 Hz.
    # The old metric's answer must not depend on that choice -- and it does, by ~59 dB.
    ladder = [0.30, 0.20, 0.12, 0.08, 0.05, 0.04, 0.03, 0.02]
    y = _tone(n, K_BIN)
    off = np.sin(2.0 * np.pi * 2500.0 * np.arange(n) / FS)
    for order, a in zip(range(2, 10), ladder):
        y = y + _tone(n, order * K_BIN, a, phase=0.7 * order)
        off = off + a * np.sin(2.0 * np.pi * order * 2500.0 * np.arange(n) / FS + 0.7 * order)
    new = metric_new(y)
    old_exact = metric_old(y, f0=F0)          # same signal, old analysis, bin-exact f0
    old_off = metric_old(off)                 # ... and as the shipped test actually places it
    rep("KA-2 harmonics only, new metric at floor",
        new["alias_db"] < -250.0, f"new = {new['alias_db']:.1f} dB")
    rep("KA-2 old metric IS contaminated (off-grid f0)",
        old_off > -60.0, f"old = {old_off:.2f} dB on a signal with ZERO alias content")
    out.append(f"        (the same signal placed bin-exact reads {old_exact:.2f} dB on the OLD "
               f"metric -- so the {old_off - old_exact:+.0f} dB is the off-grid window skirt,")
    out.append("         which is why the shipped test shows a hard -40.5 dB 'floor' at low drive)")

    # ---- KA-3: calibration. A known inharmonic tone must read its own level --
    target = -35.0
    a = 10 ** (target / 20.0)
    y = _tone(n, K_BIN) + _tone(n, 1000, a)   # 1000 is not a multiple of 853
    got = metric_new(y)["alias_db"]
    rep("KA-3 known -35.0 dB inharmonic tone recovered",
        abs(got - target) < 0.05, f"read {got:.3f} dB")

    # ---- KA-4: a settling LF transient. THE DISCRIMINATOR FOR (b) -----------
    # MasterOut is two ~0.72 Hz high-passes (tau = 0.22 s) and an asymmetric clipper steps them,
    # so the analysis window contains a decaying DC ramp. The fix is the SETTLE LENGTH, not the
    # window: an exponential is not periodic in M, so no window choice makes it disappear -- it
    # has to have decayed away before the read. Both halves of that claim are gated here.
    tau = 0.22 * FS
    dc0 = 0.30
    surv_old = dc0 * np.exp(-SETTLE_S_OLD * FS / tau)   # what survives OSValidationTest's settle
    surv_new = dc0 * np.exp(-SETTLE_S_NEW * FS / tau)   # ... and what survives this tool's
    y_old = _tone(n, K_BIN) + surv_old * np.exp(-np.arange(n) / tau)
    y_new = _tone(n, K_BIN) + surv_new * np.exp(-np.arange(n) / tau)
    # differential, not absolute: the claim is that the transient adds contamination ON TOP of
    # whatever the metric's own leakage pedestal already is, so it is scored against the SAME
    # signal without the transient rather than against a number picked by hand.
    old_clean = metric_old(_tone(n, K_BIN), f0=F0)
    old_trans = metric_old(y_old, f0=F0)
    rep("KA-4 old metric charges the transient to alias",
        old_trans - old_clean > 20.0,
        f"old = {old_trans:.2f} dB vs {old_clean:.2f} without it "
        f"(+{old_trans - old_clean:.1f} dB, residual {surv_old:.3f})")
    rep("KA-4 repaired metric still would, at the OLD settle",
        metric_new(y_old)["alias_db"] > -60.0,
        f"new = {metric_new(y_old)['alias_db']:.2f} dB -- the window is NOT the fix")
    rep("KA-4 the 4 s settle IS the fix",
        metric_new(y_new)["alias_db"] < -150.0,
        f"new = {metric_new(y_new)['alias_db']:.1f} dB (residual {surv_new:.1e})")

    # ---- KA-5: MUTATION. The metric must be able to report a real floor -----
    rng = np.random.default_rng(20260731)
    noise = rng.standard_normal(n)
    sig = _tone(n, K_BIN)
    # scale so inharmonic power sits 17 dB below the fundamental's power
    p_sig = (np.abs(np.fft.rfft(sig)) ** 2)[K_BIN]
    noise = noise * np.sqrt(p_sig * 10 ** (-17.0 / 10.0) / (np.abs(np.fft.rfft(noise)) ** 2).sum())
    got = metric_new(sig + noise)["alias_db"]
    rep("KA-5 mutation: real -17 dB broadband alias IS reported",
        abs(got - (-17.0)) < 0.6, f"read {got:.3f} dB")

    # ---- KA-6: the rectangular read is start-offset invariant ---------------
    y = (_tone(n, K_BIN, length=n + 64)
         + _tone(n, 5 * K_BIN, 0.2, length=n + 64)
         + _tone(n, 1000, 0.01, length=n + 64))
    v = [metric_new(y[s:s + n])["alias_db"] for s in (0, 7, 31, 64)]
    rep("KA-6 read invariant to analysis start offset",
        max(v) - min(v) < 1e-6, f"spread {max(v) - min(v):.2e} dB over 4 offsets")

    return fails, out


