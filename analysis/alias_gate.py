# CONVERGENCE — is the 48 k / 8x inharmonic floor a discretisation artefact?
# ---------------------------------------------------------------------------
def converge(amps=(0.35, 0.5), jobs=None):
    """Compare the 48 k/8x inharmonic floor against a 192 k/8x reference.

    At 192 kHz base the chain's own decimation is 32x further from the audible band, so anything
    it still shows below 24 kHz is NOT fold-down. The bin grid is identical in Hz (192000/65536 ==
    48000/16384), so the two reads are compared over the same frequencies with no resampling.
    """
    jobs_list = [(a, sn) for sn in (SHIPPED_SATNEG, PRIOR_SATNEG) for a in amps]

    def one(job):
        a, sn = job
        y48 = render_sine(a, 8, sn, fs=FS, k=K_BIN, n=M)
        r48 = metric_new(y48)
        y192 = render_sine(a, 8, sn, fs=4 * FS, k=4 * K_BIN, n=4 * M)
        r192 = metric_new(y192, k=4 * K_BIN, fs=4 * FS, n=4 * M)
        # restrict the 192 k read to 0-24 kHz, i.e. the band 48 k can represent at all
        e, harm, other = r192["_e"], r192["_harm"], r192["_other"]
        nb = len(e)
        keep = np.arange(nb) <= (nb - 1) // 4
        ref = _db(e[other & keep].sum(), e[harm & keep].sum())
        return {"amp": a, "satneg": sn, "at48k": r48["alias_db"], "ref192k": ref,
                "excess": r48["alias_db"] - ref}

    rows = pmap(one, jobs_list, jobs=jobs)
    print("\n  CONVERGENCE: 48 k/8x vs a 192 k/8x reference, both read 0-24 kHz")
    print("    excess = how much inharmonic energy the 48 k render has that the 192 k one does")
    print("             NOT -- i.e. the part that is genuinely fold-down.")
    print("     satneg   amp |   48k/8x    192k/8x     excess")
    for r in sorted(rows, key=lambda r: (-r["satneg"], r["amp"])):
        print(f"    {r['satneg']:>8}  {r['amp']:.2f} | {r['at48k']:8.2f}  {r['ref192k']:9.2f}  "
              f"{r['excess']:+9.2f}")
    return rows


# ---------------------------------------------------------------------------
# LOCUS — where the inharmonic energy actually sits, and what predicts it
# ---------------------------------------------------------------------------
def fold_bin(order, k, n):
    """Bin that harmonic `order` of a bin-`k` tone lands on after folding in an n-point DFT."""
    b = (order * k) % n
    return min(b, n - b)


def locus(amp=0.35, os_factor=8, satneg=SHIPPED_SATNEG, top=6, ks=(K_BIN,)):
    """Attribute each dominant inharmonic bin to a harmonic order folding at the OS rate.

    This is the discriminator between "aliasing" and "an autonomous oscillation beating with the
    tone": both put energy at the same bins for ONE f0 (because `n*f0 - m*fs_os` is itself a
    sideband offset), so f0 is MOVED. A fold tracks |n*f0 - m*fs_os| and shifts; a beat note does
    not. Nothing here is fitted -- the predicted bin is arithmetic.
    """
    rows = []
    for k in ks:
        f0 = k * FS / M
        y = render_sine(amp, os_factor, satneg, k=k)
        r = metric_new(y, k=k)
        e, other = r["_e"], r["_other"]
        idx = np.argsort(e * other)[::-1][:top]
        n_centre = int(round(os_factor * FS / f0))
        peaks = []
        for b in idx:
            # nearest harmonic order whose fold lands on this bin
            cands = {o: fold_bin(o, k, M) for o in range(max(1, n_centre - 8), n_centre + 9)}
            best = min(cands, key=lambda o: abs(cands[o] - b))
            peaks.append({"bin": int(b), "hz": b * FS / M,
                          "db_re_h1": 10 * np.log10(e[b] / e[k]),
                          "fold_order": best, "fold_bin": cands[best],
                          "offset_from_h1_hz": b * FS / M - f0})
        rows.append({"k": k, "f0": f0, "alias_db": r["alias_db"], "peaks": peaks})
    return rows


def print_locus(rows, os_factor, satneg):
    print(f"\n  LOCUS of the inharmonic energy  (amp 0.35, {os_factor}x, jfetSatNeg={satneg})")
    print(f"    fold_bin = |order*f0 - m*{os_factor}*fs| expressed as an M-point bin -- ARITHMETIC,")
    print("    not a fit. If it tracks across f0, the energy is fold-down; if the offset from H1")
    print("    is instead constant, it is a beat note against something autonomous.")
    for r in rows:
        print(f"\n    f0 = {r['f0']:.2f} Hz   alias = {r['alias_db']:.2f} dB")
        print("        bin       Hz    dB re H1 |  fold order  predicted bin  |  offset from H1")
        for p in r["peaks"]:
            hit = "==" if p["bin"] == p["fold_bin"] else "!="
            print(f"      {p['bin']:5d} {p['hz']:9.2f}  {p['db_re_h1']:9.2f} |  H{p['fold_order']:<9d}"
                  f" {p['fold_bin']:6d} {hit}   |  {p['offset_from_h1_hz']:+10.2f} Hz")


