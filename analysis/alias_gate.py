AMPS = [0.05, 0.1, 0.2, 0.35, 0.5, 0.7]
FACTORS = [2, 4, 8]


def _measure_one(job):
    amp, fac, sn = job
    y_new = render_sine(amp, fac, sn, settle_s=SETTLE_S_NEW)
    y_old = render_sine(amp, fac, sn, settle_s=SETTLE_S_OLD)
    r = strip(metric_new(y_new))
    r.update({"amp": amp, "os": fac, "satneg": sn,
              "old_db": metric_old(y_old, f0=F0),
              "new_on_old_window_db": metric_new(y_old)["alias_db"],
              "lf_on_old_window_db": metric_new(y_old)["lf_db"]})
    return r


def measure(jobs=None):
    grid = [(a, f, sn) for sn in (SHIPPED_SATNEG, PRIOR_SATNEG) for a in AMPS for f in FACTORS]
    rows = pmap(_measure_one, grid, jobs=jobs)
    return rows


def print_measure(rows):
    by = {(r["satneg"], r["amp"], r["os"]): r for r in rows}
    print("\n  ALIAS/SIGNAL (dB) -- same renders, three analyses")
    print("    old      = OSValidationTest's metric (Hann, +-3 bins, 0.3 s settle)")
    print("    +LF      = repaired metric on the OLD 0.3 s window, LF bucket INCLUDED")
    print("    new      = repaired metric, 4 s settle, LF bucket EXCLUDED  <- the answer")
    print("    lf       = the LF/settling bucket the old metric was charging to alias")
    for sn in (SHIPPED_SATNEG, PRIOR_SATNEG):
        tag = "SHIPPED jfetSatNeg=1.9" if sn == SHIPPED_SATNEG else "PRIOR   jfetSatNeg=0.76054"
        print(f"\n  --- {tag} ---")
        print("     amp |        2x                 |        4x                 |        8x")
        print("         |  old    +LF    new    lf  |  old    +LF    new    lf  |  old    +LF    new    lf")
        for a in AMPS:
            cells = []
            for f in FACTORS:
                r = by[(sn, a, f)]
                cells.append(f"{r['old_db']:6.1f} {r['new_on_old_window_db']:6.1f} "
                             f"{r['alias_db']:6.1f} {r['lf_db']:5.1f}")
            print(f"    {a:.2f} | " + " | ".join(cells))

    print("\n  THE ATTRIBUTED DELTA (shipped - prior), on the repaired metric:")
    print("     amp |    2x      4x      8x   |   old-metric delta at 8x")
    for a in AMPS:
        d = [by[(SHIPPED_SATNEG, a, f)]["alias_db"] - by[(PRIOR_SATNEG, a, f)]["alias_db"]
             for f in FACTORS]
        dold = (by[(SHIPPED_SATNEG, a, 8)]["old_db"] - by[(PRIOR_SATNEG, a, 8)]["old_db"])
        print(f"    {a:.2f} | " + "  ".join(f"{x:+6.2f}" for x in d) + f"   |  {dold:+6.2f}")


