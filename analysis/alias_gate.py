#!/usr/bin/env python3.11
"""ALIAS GATE — a real instrument for the `OSValidationTest` aliasing number.

Session 92, opened by CLAUDE.md "Open work" item 6.

WHY THIS EXISTS
---------------
Shipping `jfetSatNeg` 0.76054 -> 1.9 in session 91 moved `OSValidationTest`'s 8x alias/signal
figure at amp 0.35 from **-23.6 to -17.3 dB**, the first movement in 46 sessions. Attribution is
exact (reverting that one constant reproduces the old record to the digit), but **whether the
number measures aliasing at all was never established**. The handover lists three reasons to
doubt it and one reason to believe it, and `measurement-discipline.md` is explicit that an
argument for why an instrument must be wrong is not a measurement of it being wrong
(`instrument-defect-is-a-hypothesis`, s90) -- so this tool measures the instrument first, against
signals whose alias content is known by construction, and only then measures the chain.

WHAT THE OLD METRIC DOES (reimplemented verbatim as `metric_old`, so the two can be run on the
SAME samples and the difference is the analysis, never the render):

  * renders a 2500 Hz sine at fs = 48000 through `PedalDSP`, discards 0.3 s, keeps 32768 samples
  * Hann-windows the FIRST 16384 of them, takes |FFT|
  * calls a bin "signal" if it is within +-3 bins of an integer multiple of f0, "alias" otherwise
  * reports 10*log10(alias_power / signal_power)

Three things in that are not properties of the chain:

  (a) **f0 is not bin-exact.** 2500 / (48000/16384) = 853.333 bins. Every harmonic whose order is
      not a multiple of 3 sits a third of a bin off-grid, so its Hann skirt runs past the +-3 bin
      mask and is counted as alias. The leaked fraction is fixed, so the metric has a PEDESTAL --
      and the pedestal grows with harmonic content, which is exactly what `jfetSatNeg` changes.
  (b) **0.3 s is not settled.** `MasterOut` is two ~0.72 Hz high-passes (tau = 0.22 s). An
      asymmetric clipper puts a DC step into them, so the analysis window still contains a
      decaying LF ramp -- energy at bins 1..50, where `round(f/f0) == 0` classifies it as alias.
      DC offset is generated by even-order asymmetry, i.e. again exactly what `jfetSatNeg` changes.
  (c) real aliasing.

`metric_new` removes (a) and (b) by construction rather than by tolerance:

  * f0 is chosen bin-exact (f0 = K*fs/M), so the stimulus is periodic in exactly M samples. The
    chain is time-invariant and the OS factor divides M, so the steady-state output is periodic in
    M too -- a RECTANGULAR window then has zero leakage and every harmonic AND every fold of a
    harmonic lands dead on a bin. No mask width is needed and none is used.
  * the settle is 4 s (18 tau), and the LF region is reported as its own bucket instead of being
    summed into "alias", so any residual shows up labelled rather than disguised.
  * harmonic bins are {n*K : n*K < M/2}. A harmonic above Nyquist folds to |n*K - M| and is
    correctly counted as ALIAS, because a band-limited model would not produce it at all.

GATES (`--selftest`) -- every one is a signal whose answer is known before it is measured, and
each is chosen to make a DIFFERENT hypothesis fail rather than to make the new metric look good.
KA-2 and KA-4 are the discriminators for (a) and (b): the old metric must FAIL them and the new
one must pass, otherwise this tool is not measuring what it claims. KA-5 is the mutation test --
a metric that cannot report a real alias floor is useless no matter how clean it reads.

Run:
    python3.11 analysis/alias_gate.py --selftest
    python3.11 analysis/alias_gate.py --measure            # the amp x OS x constant grid
    python3.11 analysis/alias_gate.py --converge           # 48 k/8x vs a 192 k/8x reference
"""
