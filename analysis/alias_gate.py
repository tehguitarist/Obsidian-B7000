# TONE SWEEP — is the bad number a rare coincidence or the normal case?
# ---------------------------------------------------------------------------
SWEEP_KS = [68, 102, 137, 171, 205, 239, 273, 341, 410, 512, 614, 683, 785, 853,
            956, 1024, 1109, 1229, 1365, 1502, 1706]


def sweep(os_factors=(2, 8), amp=0.35, jobs=None):
    grid = [(k, f, sn) for sn in (SHIPPED_SATNEG, PRIOR_SATNEG) for f in os_factors for k in SWEEP_KS]

    def one(job):
        k, f, sn = job
        y = render_sine(amp, f, sn, k=k)
        r = metric_new(y, k=k)
        return {"k": k, "f0": k * FS / M, "os": f, "satneg": sn, "alias_db": r["alias_db"]}

    rows = pmap(one, grid, jobs=jobs)
    by = {(r["satneg"], r["os"], r["k"]): r["alias_db"] for r in rows}

    # A fundamental that exactly divides fs puts every harmonic AND every fold on a harmonic bin,
    # so inharmonic content is impossible BY CONSTRUCTION and the row reads -200 dB and below.
    # Flag and exclude, rather than let a spectacular meaningless number into a median.
    def degenerate(k):
        return abs(FS / (k * FS / M) - round(FS / (k * FS / M))) < 1e-9

    live = [k for k in SWEEP_KS if not degenerate(k)]
    print(f"\n  TONE SWEEP: alias/signal (dB) vs fundamental, amp {amp}")
    print("    Every f0 is bin-exact, so no row carries the off-grid pedestal.")
    print(f"    [deg] = f0 divides fs exactly -> no fold can be inharmonic; excluded from the "
          f"summary ({len(SWEEP_KS) - len(live)} of {len(SWEEP_KS)} rows).")
    hdr = "      f0 (Hz) |" + "".join(f"  {f}x ship  {f}x prior  delta |" for f in os_factors)
    print(hdr)
    for k in SWEEP_KS:
        cells = []
        for f in os_factors:
            s, p = by[(SHIPPED_SATNEG, f, k)], by[(PRIOR_SATNEG, f, k)]
            cells.append(f" {s:8.1f}  {p:9.1f} {s - p:+6.1f} |")
        print(f"    {k * FS / M:9.1f} |" + "".join(cells)
              + ("  [deg]" if degenerate(k) else ""))
    for f in os_factors:
        s = np.array([by[(SHIPPED_SATNEG, f, k)] for k in live])
        p = np.array([by[(PRIOR_SATNEG, f, k)] for k in live])
        print(f"    {f}x  median ship {np.median(s):6.1f}  prior {np.median(p):6.1f}   "
              f"worst ship {s.max():6.1f}  prior {p.max():6.1f}   "
              f"median delta {np.median(s - p):+5.2f}  worst delta {(s - p).max():+5.2f}")
    return rows


# ---------------------------------------------------------------------------
# PERIODICITY — separates deterministic fold-down from an aperiodic regime
# ---------------------------------------------------------------------------
def periodicity(amp=0.35, os_factors=(2, 8), jobs=None):
    """Is the settled output actually periodic in M samples?

    The bin-exact stimulus is periodic in M, and the chain is time-invariant, so a WELL-BEHAVED
    model's settled output must repeat exactly every M samples. It does not have to put its energy
    on harmonic bins to do that -- a subharmonic or chaotic regime is still a regime -- so this
    test separates two things the spectrum alone cannot:

      residual ~ 1e-9  ->  exactly periodic; every inharmonic bin is deterministic FOLD-DOWN.
      residual >> 0    ->  the output does not repeat at all; the inharmonic energy is an
                           APERIODIC regime of the discrete map, which no amount of window or
                           mask arithmetic will explain and which oversampling does not fix.

    Run it before attributing any inharmonic reading to aliasing.
    """
    grid = [(k, f, sn) for sn in (SHIPPED_SATNEG, PRIOR_SATNEG) for f in os_factors
            for k in SWEEP_KS]

    def one(job):
        k, f, sn = job
        n = M
        settle = int(np.ceil(SETTLE_S_NEW * FS / n)) * n
        y = _render_raw(amp, f, sn, k, settle + 2 * n + 4096)
        a, b = y[settle:settle + n], y[settle + n:settle + 2 * n]
        rms = max(float(np.sqrt(np.mean(a ** 2))), 1e-30)
        return {"k": k, "f0": k * FS / M, "os": f, "satneg": sn,
                "resid": float(np.sqrt(np.mean((b - a) ** 2)) / rms),
                "alias_db": metric_new(a, k=k)["alias_db"]}

    rows = pmap(one, grid, jobs=jobs)
    by = {(r["satneg"], r["os"], r["k"]): r for r in rows}
    print(f"\n  PERIODICITY vs FOLD-DOWN, amp {amp}   (resid = ||y[n+M] - y[n]|| / ||y||)")
    print("    resid ~1e-9 = exactly periodic (float32 WAV floor) -> deterministic fold-down")
    print("    resid >1e-4 = APERIODIC regime; the spectrum cannot be read as aliasing")
    hdr = "      f0 (Hz) |" + "".join(f"   {f}x ship        {f}x prior    |" for f in os_factors)
    print(hdr + "\n              |" + "".join("  alias   resid   alias   resid |" for _ in os_factors))
    for k in SWEEP_KS:
        cells = []
        for f in os_factors:
            for sn in (SHIPPED_SATNEG, PRIOR_SATNEG):
                r = by[(sn, f, k)]
                cells.append(f" {r['alias_db']:7.1f} {r['resid']:7.1e}")
        print(f"    {k * FS / M:9.1f} |" + "".join(cells))
    for f in os_factors:
        for sn in (SHIPPED_SATNEG, PRIOR_SATNEG):
            res = np.array([by[(sn, f, k)]["resid"] for k in SWEEP_KS])
            print(f"    {f}x jfetSatNeg={sn}: aperiodic (resid > 1e-4) in {(res > 1e-4).sum()}"
                  f"/{len(res)} tones, worst {res.max():.2e}")
    return rows


def _render_raw(amp, os_factor, satneg, k, total, fs=FS, n=M, drive=0.85):
    """Render `total` samples of a bin-exact sine and return the whole output (no windowing)."""
    tmpdir = tempfile.mkdtemp(prefix="alias_gate_")
    x = (amp * np.sin(2.0 * np.pi * k * np.arange(total) / n)).astype(np.float32)
    inp, outp = os.path.join(tmpdir, "i.wav"), os.path.join(tmpdir, "o.wav")
    wavfile.write(inp, int(fs), x)
    cmd = [RENDER_BIN, "--in", inp, "--out", outp, "--os", str(os_factor),
           "--input-ref", "1", "--output-makeup", "1", "--blend", "1", "--level", "1",
           "--drive", str(drive), "--master", "1", "--fit", f"jfetSatNeg={satneg}"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"OfflineRender failed\n{r.stderr}")
    _, y = wavfile.read(outp)
    y = np.asarray(y, dtype=float)
    return y[:, 0] if y.ndim > 1 else y


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--measure", action="store_true")
    ap.add_argument("--converge", action="store_true")
    ap.add_argument("--locus", action="store_true",
                    help="attribute the inharmonic peaks to folded harmonic orders, at 3 f0")
    ap.add_argument("--sweep", action="store_true",
                    help="alias floor vs fundamental, shipped vs prior jfetSatNeg")
    ap.add_argument("--periodicity", action="store_true",
                    help="deterministic fold-down vs an aperiodic regime, per tone")
    ap.add_argument("--json", default=None, help="write the measured rows here")
    add_jobs_arg(ap)
    a = ap.parse_args()

    if not (a.selftest or a.measure or a.converge or a.locus or a.sweep or a.periodicity):
        ap.error("pick at least one of --selftest / --measure / --converge / --locus / --sweep"
                 " / --periodicity")

    print(f"  geometry: fs = {FS:.0f}  M = {M}  K = {K_BIN}  f0 = {F0:.4f} Hz  "
          f"bin = {FS / M:.4f} Hz")

    rc = 0
    if a.selftest:
        print("\n  SELF-TEST (known-answer gates)")
        fails, lines = selftest()
        print("\n".join(lines))
        print(f"\n  {'ALL GATES PASS' if fails == 0 else f'{fails} GATE FAILURE(S)'}")
        rc |= (1 if fails else 0)
        if fails:
            return rc   # never measure with a failing instrument

    out = {}
    if a.measure:
        if not os.path.exists(RENDER_BIN):
            sys.exit(f"OfflineRender not built: {RENDER_BIN}")
        rows = measure(jobs=a.jobs)
        print_measure(rows)
        out["measure"] = rows
    if a.locus:
        rows = locus(ks=(683, K_BIN, 1109))
        print_locus(rows, 8, SHIPPED_SATNEG)
        out["locus"] = rows
    if a.sweep:
        out["sweep"] = sweep(jobs=a.jobs)
    if a.periodicity:
        out["periodicity"] = periodicity(jobs=a.jobs)
    if a.converge:
        out["converge"] = converge(jobs=a.jobs)
    if a.json and out:
        with open(a.json, "w") as f:
            json.dump(out, f, indent=1)
        print(f"\n  wrote {a.json}")
    return rc


if __name__ == "__main__":
    sys.exit(main())
